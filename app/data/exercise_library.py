# Primary demonstration source.
VIDEO_BASE = "https://www.muscleandstrength.com/exercises"


def ms(path: str) -> str:
    """A verified Muscle & Strength guide page."""
    return f"{VIDEO_BASE}/{path}"


def mw(slug: str) -> str:
    """A verified MuscleWiki exercise page (secondary source)."""
    return f"https://musclewiki.com/exercise/{slug}"


def yt(name: str) -> str:
    """Fallback for movements the primary source does not cover."""
    return f"https://www.youtube.com/results?search_query={quote_plus(name + ' exercise form tutorial')}"


